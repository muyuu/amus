use super::keys::TextKey;
use super::words::ja::JapaneseWords as W;

/// キーを現在言語の文字列に変換する。
/// `TextKey` 全件を網羅し、コンパイル時に翻訳漏れを防ぐ。
pub fn translate(key: TextKey) -> String {
    use TextKey::*;
    match key {
        AppTitle => W::APP_TITLE.to_string(),
        MenuFile => W::FILE.to_string(),
        MenuNewGame => format!("{}{}", W::NEW, W::GAME),
        MenuLoadGame => format!("{}を{}", W::GAME, W::LOAD),
        MenuSaveGame => format!("{}を{}", W::GAME, W::SAVE),
        MenuLanguage => W::LANGUAGE.to_string(),
        SidebarTurnManagement => format!("{}{}", W::TURN, W::MANAGEMENT),
        SidebarAddNewTurn => format!("新しい{}を{}", W::TURN, W::ADD),
        SidebarPlayers => format!("{}一覧", W::PLAYER),
        SidebarStartGamePrompt => format!("{}を{}してください", W::GAME, W::START),
        SidebarTurnPrefix => W::TURN.to_string(),
        SidebarCurrentTurnPrefix => format!("▶ {}", W::TURN),
        SetupTitle => format!("{}{}", W::GAME, W::SETTINGS),
        SetupAreaSelection => W::AREA.to_string(),
        SetupPlayerSettings => format!("{}{}", W::PLAYER, W::SETTINGS),
        SetupPlayerCount => format!("{}{}:", W::PLAYER, W::COUNT),
        SetupPlayerConfig => format!("各{}の{}:", W::PLAYER, W::CONFIG),
        SetupConfigNote => "（実装中: デフォルト設定で開始可能）".to_string(),
        SetupPlayerName => W::NAME.to_string(),
        SetupPlayerColor => W::COLOR.to_string(),
        SetupStartGame => format!("{}{}", W::GAME, W::START),
        SetupCancel => W::CANCEL.to_string(),
        MainDrawingMode => format!("{}{}:", W::DRAWING, W::MODE),
        MainDrawingNone => W::NONE.to_string(),
        MainDrawingClickLine => format!("{}で{}", W::CLICK, W::LINE),
        MainDrawingFreehand => W::FREEHAND.to_string(),
        MainDiscussionInfo => format!("{}{}情報", W::DISCUSSION, W::TURN),
        MainKilledPlayer => format!("{}{}:", W::KILLED, W::PLAYER),
        MainKillLocation => format!("殺害{}（証言）:", W::LOCATION),
        MainLocationUnset => W::UNSET.to_string(),
        MainSetLocationBtn => format!("マップ上で{}して{}", W::CLICK, W::SET),
        MainLocationNote => "（実装中: マップ上で右クリックで設定予定）".to_string(),
        MainNotes => format!("{}:", W::NOTES),
        MainNoSelection => W::NONE.to_string(),
        MainSelectPrompt => "{}してください".to_string(),
        MainStatusAlive => W::ALIVE.to_string(),
        MainStatusDead => W::DEAD.to_string(),
        MainWelcomeTitle => W::APP_TITLE.to_string(),
        MainWelcomeMessage => format!("新しい{}を{}してください", W::GAME, W::START),
        PlayerInfoButtonDone => "済み".to_string(),
        PlayerInfoButtonNotDone => "会議".to_string(),
        EraserButton => W::ERASER.to_string(),
        Sabotage => W::SABOTAGE.to_string(),
        SabotageComms => W::SABOTAGE_COMMS.to_string(),
        SabotageLights => W::SABOTAGE_LIGHTS.to_string(),
        SabotageReactor => W::SABOTAGE_REACTOR.to_string(),
        SabotageO2 => W::SABOTAGE_O2.to_string(),
        SabotageDoors => W::SABOTAGE_DOORS.to_string(),
        VoiceMemoTitle => W::VOICE_MEMO.to_string(),
        VoiceMemoModelDownloading => format!("⏳ {}を{}...", W::MODEL, W::DOWNLOADING),
        VoiceMemoModelNotFound => format!("⚠ {}が見つかりません", W::WHISPER_MODEL),
        VoiceMemoModelRequired => format!("{}には{}が必要です", W::VOICE_RECOGNITION, W::MODEL),
        VoiceMemoDownloadModel => format!("📥 {}を{}", W::MODEL, W::DOWNLOAD),
        VoiceMemoMicUnavailable => format!("⚠ {}が利用できません", W::MIC),
        VoiceMemoEnd => W::END.to_string(),
        VoiceMemoTranscribing => format!("⏳ {}...", W::TRANSCRIBING),
        VoiceMemoStartTurn => format!("▶ {}{}", W::TURN, W::START),
        VoiceMemoClear => format!("🗑 {}", W::CLEAR),
        VoiceMemoError => W::ERROR.to_string(),
        VoiceMemoStartPrompt => format!("{}を{}してください", W::TURN, W::START),
        VoiceMemoRecordHint => W::RECORD_BUTTON_HINT.to_string(),
        VoiceMemoMemoCount => W::NOTES.to_string(),
        VoiceMemoTurnTime => format!("{}{}", W::TURN, W::TIME),
        SettingsTitle => W::SETTINGS.to_string(),
        SettingsTabGame => W::GAME.to_string(),
        SettingsTabDisplay => W::DISPLAY.to_string(),
        SettingsTabVoice => W::VOICE.to_string(),
        SettingsTabApp => W::APP.to_string(),
        SettingsRouteLineWidth => format!("軌跡の{}", W::WIDTH),
        SettingsUiScale => "UI拡大率".to_string(),
        SettingsUiScaleAuto => "DPIに追従".to_string(),
        SettingsVoicePlaceholder => "設定できる項目はまだありません".to_string(),
        SettingsInputDevice => format!("{}{}", W::INPUT, W::DEVICE),
        SettingsInputDeviceDefault => format!("{}の{}", W::DEFAULT, W::DEVICE),
        SettingsAppVersion => W::VERSION.to_string(),
        SettingsDebugToggle => "🐛 デバッグ表示".to_string(),
        SettingsClose => W::CLOSE.to_string(),
        SettingsResetGame => format!("{}を{}", W::GAME, W::RESET),
    }
}
